r"""act1_paired_tables.py -- render `act1_paired.json` into the markdown tables the chapter needs.

Pure formatting: it reads the JSON produced by `act1_paired.py` and writes
`docs/results/ACT1_PAIRED_CI.md`. No statistics are computed here, so the numbers in the document and
the numbers in the machine-readable JSON cannot drift.
"""
import os
import sys
import json

_HERE = os.path.dirname(os.path.abspath(__file__))
_ROOT = os.path.abspath(os.path.join(_HERE, "..", ".."))
IN = os.path.join(_ROOT, "experiments", "baselines", "interview", "act1_paired.json")
OUTMD = os.path.join(_ROOT, "docs", "results", "ACT1_PAIRED_CI.md")
BUDGETS = (1, 2, 4, 8, 16)


def cell(e):
    if e is None:
        return "--"
    mark = "**" if e["separates"] else ""
    return f"{mark}{e['delta']:+.4f}{mark} [{e['lo']:+.4f}, {e['hi']:+.4f}]"


def block(res, section, rows, axes=("full", "tail"), budgets=BUDGETS, prefix="ours"):
    """rows: list of (label, comparison-suffix). Emits one table per axis."""
    out = []
    d = res[section]
    for ax in axes:
        out.append(f"\n**{ax} NDCG@10**\n")
        out.append("| comparison | " + " | ".join(f"k={k}" for k in budgets) + " |")
        out.append("|---|" + "---|" * len(budgets))
        for label, suf in rows:
            cells = []
            for k in budgets:
                key = f"{prefix}/{ax}/k{k}/{suf}"
                hit = d.get(key)
                if hit is None:                       # D2's comparator name varies per cell
                    hit = next((v for kk, v in d.items()
                                if kk.startswith(f"{prefix}/{ax}/k{k}/{suf}")), None)
                cells.append(cell(hit))
            out.append(f"| {label} | " + " | ".join(cells) + " |")
    return out


def main():
    res = json.load(open(IN))
    m = res["meta"]
    L = []
    A = L.append
    A("# Act 1: paired bootstrap CIs on every selector-vs-static comparison")
    A("")
    A(f"Generated by `src/baselines/act1_paired.py` (analysis) + `act1_paired_tables.py` (render) "
      f"from `experiments/baselines/interview/act1_paired.json`.")
    A("")
    A(f"* **Form:** {m['form']}. Resample the {m['n_test_users']:,} test users with replacement, "
      f"recompute the per-user difference, take the 2.5/97.5 percentiles of the difference means. "
      f"NEVER the unpaired `1.96*sqrt(2)*SE` form (`ARM_N_PHASE1.md` sec 4b).")
    A(f"* **Resamples:** {m['boot']:,}. **Seed:** {m['seed']}.")
    A(f"* **Contract:** consumer = certified tower `{m['snapshot']}` (arch {m['arch']}), NO-FLOOR, "
      f"{m['n_test_users']:,} test users, fixed arm-N candidate pool. "
      f"Scored users: {m['n_full_scored']:,} (full), {m['n_tail_scored']:,} (tail -- users whose "
      f"held-out set is all head have no tail target and are dropped by the metric, identically for "
      f"every arm).")
    A(f"* **Selector seeds reproduced:** ST.SEED={m['st_seed']}, ts_seed={m['ts_seed']}, "
      f"ucb_alpha={m['ucb_alpha']}.")
    dr = m["control_drift"]
    A(f"* **Control:** " + ("every recomputed cell mean reproduces the stored Act-1 tables to 1e-9."
                            if not dr else
                            f"{len(dr)} of {2 * len(m['cells_present'])} cell/axis values differ from "
                            f"the stored table; **every one of them is a `glm_ucb` or `thompson` "
                            f"cell** (see the reproducibility note below). Largest |diff| "
                            f"{max(abs(d['diff']) for d in dr):.4f}."))
    A(f"* **Self-test:** an arm paired against itself gives delta 0.0000, CI [0.0000, 0.0000] -- "
      f"{'PASS' if m['self_test_pass'] else 'FAIL'} "
      f"({len(res['self_test'])} self-comparisons, all exactly zero).")
    A("")
    A("**Bold** = the CI excludes zero (SEPARATES). Unbolded = not separated at 95%.")
    A("")
    if dr:
        A("## Reproducibility note: the two bandit selectors are not seed-stable")
        A("")
        A("Re-running the identical command reproduces every `entropy0` / `helf` / `popularity` / "
          "`pure_entropy` / `random_bank` / `random_catalog` / `eddi_ig` cell **exactly** (bit-level, "
          "to 1e-9) but reproduces **no** `glm_ucb` or `thompson` cell exactly. Cause: "
          "`ials._fit_model` constructs `AlternatingLeastSquares(...)` with **no `random_state`**, so "
          "the frozen iALS basis `Y` that `belief_mf` hands both bandits is re-drawn on every "
          "process. The selectors' own seeds (`ts_seed=98765`, `alpha=1.0`) are honoured; the "
          "*posterior they are seeded against* is not.")
        A("")
        A("Consequence for these CIs: the pairing is still valid and the intervals are still correct "
          "**conditional on this run's basis** — both arms of every comparison come from one process "
          "and the static comparator is exactly reproducible. But the bandit rows carry an additional "
          "basis-to-basis variance component that a within-run paired bootstrap cannot see. The two "
          "runs available give a direct read on its size (below): up to $\\pm.0026$, which is "
          "comparable to the CI half-widths. **Any chapter claim about a `glm_ucb` or `thompson` "
          "number to four decimals is currently unreproducible**; the fix is one `random_state=` "
          "argument plus a re-run.")
        A("")
        A("| cell | this run | stored table | diff |")
        A("|---|---|---|---|")
        for d in sorted(dr, key=lambda x: -abs(x["diff"])):
            A(f"| `{d['cell']}` | {d['recomputed']:.4f} | {d['stored']:.4f} | {d['diff']:+.4f} |")
        A("")

    A("## D1. Consumer `ours`: adaptive selector MINUS entropy0-static")
    L += block(res, "D1_vs_entropy0_static",
               [("glm_ucb", "glm_ucb-minus-entropy0_static"),
                ("thompson", "thompson-minus-entropy0_static"),
                ("eddi_ig", "eddi_ig-minus-entropy0_static")])
    A("")

    A("## D2. Consumer `ours`: adaptive selector MINUS the strongest static in this contract")
    A("")
    A("Strongest static chosen per (budget, axis) by point estimate on the same data: "
      + ", ".join(f"`{k}`={v}" for k, v in sorted(res["strongest_static"].items())) + ".")
    A("Choosing the comparator by its own maximum biases it upward, i.e. AGAINST the adaptive "
      "selector -- the conservative direction for a \"static wins\" claim, and the anti-conservative "
      "direction for any \"adaptive wins\" claim, so read D2 only as a lower bound on the adaptive gap.")
    L += block(res, "D2_vs_strongest_static",
               [("glm_ucb", "glm_ucb-minus-BEST_STATIC"),
                ("thompson", "thompson-minus-BEST_STATIC"),
                ("eddi_ig", "eddi_ig-minus-BEST_STATIC")])
    A("")

    A("## D3. The static ladder's own separations (consumer `ours`)")
    pairs = [("entropy0", "popularity"), ("popularity", "helf"), ("entropy0", "helf"),
             ("entropy0", "pure_entropy"), ("entropy0", "random_bank"), ("entropy0", "random_catalog"),
             ("popularity", "pure_entropy"), ("popularity", "random_bank"),
             ("popularity", "random_catalog"),
             ("helf", "pure_entropy"), ("helf", "random_bank"), ("helf", "random_catalog"),
             ("pure_entropy", "random_bank"), ("random_bank", "random_catalog"),
             ("pure_entropy", "random_catalog")]
    L += block(res, "D3_static_ladder", [(f"{x} - {y}", f"{x}-minus-{y}") for x, y in pairs])
    A("")

    A("## D4. The `golbandi_leaf` reversal")
    A("")
    A("On the leaf consumer the chapter claims Thompson BEATS the static order (.1974/.0750 vs "
      ".1686/.0677 at k=8). Positive delta = the adaptive selector wins.")
    L += block(res, "D4_golbandi_reversal",
               [("thompson", "thompson-minus-entropy0_static"),
                ("glm_ucb", "glm_ucb-minus-entropy0_static"),
                ("eddi_ig", "eddi_ig-minus-entropy0_static")],
               budgets=(1, 2, 4, 8), prefix="golbandi_leaf")
    A("")

    A("## Point estimates behind every difference")
    A("")
    A("| cell | full | tail |")
    A("|---|---|---|")
    for key in sorted(res["points"]):
        p = res["points"][key]
        A(f"| `{key.replace('|', ' / ')}` | {p['full']:.4f} | {p['tail']:.4f} |")
    A("")

    os.makedirs(os.path.dirname(OUTMD), exist_ok=True)
    with open(OUTMD, "w", encoding="utf-8") as f:
        f.write("\n".join(L) + "\n")
    print(f"wrote {OUTMD} ({len(L)} lines)")


if __name__ == "__main__":
    main()
