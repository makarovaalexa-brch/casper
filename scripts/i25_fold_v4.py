"""i25_fold_v4.py -- FOLD-V4: the DE-OOD belief encoder (per DESIGN_SHEET_FOLD_V4_DEOOD.md).

THE BUG (v3.1): interviews were sampled with on_profile=0.7 (privileged -- the interviewer is assumed
to already know the user's taste region). At deployment the blind/adaptive policies land OFF-profile,
so the fold is OOD: elicitation barely lifts (+0.02) and the expected-gain order collapses (-0.006).

THE FIX (author-designed, single fixed length B=8): retrain the SAME FoldV31 architecture on interviews
generated by an ENSEMBLE of REAL selection strategies run through the REAL gated v2.1 answerer (the
arena world: fitted v2.1 knowledge/value models + EASE backbone + 2,428-question universe). Answers are
NEVER faked -- only SELECTION is randomized broadly, biased toward the HARD TAILS (off-profile / niche /
famous-refusal) where the fold currently collapses. Plus ~30% clean full profiles to keep real-profile
skill. One selection strategy (POPULARITY) + blind-EIG are HELD OUT entirely for the generalization gate.

Generation is done IN THE ARENA WORLD (arena_core.Arena) so the fold trains on the ACTUAL deployment
distribution -- this simultaneously removes the sampler-vs-arena distribution shift v3.1 carried.

NO LLM calls. $0. Firewall: population trU users only (the 173/300 study/eval users NEVER touched);
fold training uses users [0:5000] of the seed-123 shuffle = strictly inside the arena TRAIN range,
DISJOINT from the seed-123 DEVTEST split [17000:20000] the baselines are scored on. Deterministic.

Run:
  python scripts/i25_fold_v4.py train --n_train 4000 --n_val 1000 --epochs 10
  python scripts/i25_fold_v4.py smoke
"""
